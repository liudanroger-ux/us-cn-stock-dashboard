_COMBINED_CACHE_FILE = OUTPUT_JSON

def _load_combined():
    if _COMBINED_CACHE_FILE.exists():
        try:
            with open(_COMBINED_CACHE_FILE, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            pass
    return None


def _incrementally_save(combined):
    try:
        with open(OUTPUT_JSON, "w", encoding="utf-8") as f:
            json.dump(combined, f, ensure_ascii=False, indent=2, default=str)
        now = datetime.now()
        js_content = f"// Auto-generated by collect_data.py v13 (Tencent Finance)\n"
        js_content += f"// Generated: {now.strftime('%Y-%m-%d %H:%M:%S')}\n"
        js_content += "const SECTOR_DATA = "
        js_content += json.dumps(combined, ensure_ascii=True, default=str)
        js_content += ";\n"
        with open(OUTPUT_JS, "wb") as f:
            f.write(b"\xef\xbb\xbf")
            f.write(js_content.encode("utf-8"))
        print(f"  [save] data.js updated ({now.strftime('%H:%M:%S')})", flush=True)
    except Exception as e:
        print(f"  [save] ERROR: {e}", flush=True)


