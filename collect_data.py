def collect_market(sectors_dict, names_map, label, market_type):
    """
    采集一个市场的所有数据
    market_type: "CN" | "US"
    """
    # Step 1: 构建去重 ticker 列表及腾讯代码映射
    all_tickers = []
    seen = set()
    tencent_map = {}  # tencent_sym -> raw_code
    for sector, tickers in sectors_dict.items():
        for t in tickers:
            raw = t.split(".")[0] if "." in t else t
            if raw not in seen:
                seen.add(raw)
                all_tickers.append(raw)
                if market_type == "CN":
                    tencent_sym = _cn_to_tencent(t)
                else:
                    tencent_sym = _us_to_tencent(raw)
                tencent_map[tencent_sym] = raw

    unique_count = len(all_tickers)
    print(f"[{label}] {len(sectors_dict)} sectors, {unique_count} unique tickers", flush=True)
    t0 = time.time()

    # Step 2: 腾讯财经API批量获取
    print(f"[{label}] Fetching via Tencent Finance API...", flush=True)
    tencent_syms = list(tencent_map.keys())
    tencent_data = fetch_tencent_batch(tencent_syms, batch_size=50)

    # Step 3: 构建结果
    price_data = {}
    for tencent_sym, raw_code in tencent_map.items():
        d = tencent_data.get(tencent_sym)
        if d and d.get("price", 0) > 0:
            price_data[raw_code] = {
                "code": raw_code,
                "name": names_map.get(raw_code, d.get("name", raw_code)),
                "price": d["price"],
                "change_pct": d["change_pct"],
                "market_cap": d["market_cap"],
                "pe": d["pe"],
            }

    t1 = time.time()
    filled = len(price_data)
    has_pe = sum(1 for s in price_data.values() if s.get("pe", 0) > 0)
    print(f"[{label}] Tencent done: {filled}/{unique_count} stocks, {has_pe} with PE ({t1-t0:.1f}s)", flush=True)

    # Step 4: 按板块分组，按涨跌幅降序排列
    results = {}
    for sector, tickers in sectors_dict.items():
        stocks = []
        seen_stocks = set()
        for t in tickers:
            raw = t.split(".")[0] if "." in t else t
            if raw in seen_stocks:
                continue
            seen_stocks.add(raw)
            if raw in price_data:
                stocks.append(price_data[raw])
        stocks.sort(key=lambda s: s.get("change_pct", 0) or 0, reverse=True)
        results[sector] = {
            "stocks": stocks[:30],
            "updated": datetime.now().isoformat(),
            "count": min(len(stocks), 30),
        }

    total_time = time.time() - t0
    print(f"[{label}] Done: {filled}/{unique_count} stocks, {total_time:.1f}s total", flush=True)
    return results


