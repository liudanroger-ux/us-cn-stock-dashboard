def _safe_float(val, default=0):
    """安全转换 float"""
    try:
        v = float(val)
        return v if v == v else default  # NaN check
    except (ValueError, TypeError):
        return default


def _cn_to_tencent(code_with_suffix):
    """A股代码转腾讯格式: 600519.SS → sh600519, 300750.SZ → sz300750"""
    raw = code_with_suffix.split(".")[0]
    if raw.startswith(("6", "9")):
        return f"sh{raw}"
    return f"sz{raw}"


def _us_to_tencent(ticker):
    """美股 ticker 转腾讯格式: NVDA → usNVDA"""
    return f"us{ticker.upper()}"


def fetch_tencent_batch(symbols_list, batch_size=50):
    """
    批量从腾讯财经API获取行情数据。
    symbols_list: 腾讯格式的代码列表 (如 sh600519, usNVDA)
    返回: {symbol: {name, code, price, change_pct, pe, market_cap}}
    """
    result = {}
    total = len(symbols_list)

    for i in range(0, total, batch_size):
        batch = symbols_list[i:i + batch_size]
        sym_str = ",".join(batch)
        url = f"https://qt.gtimg.cn/q={sym_str}"
        req = urllib.request.Request(url)
        req.add_header("User-Agent", "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36")
        try:
            with urllib.request.urlopen(req, timeout=15) as resp:
                data = resp.read().decode("gbk")
            lines = [l for l in data.strip().split(";") if l.strip()]
            for line in lines:
                # 提取引号内的内容
                start_q = line.find('"')
                end_q = line.rfind('"')
                if start_q < 0 or end_q <= start_q:
                    continue
                inner = line[start_q + 1:end_q].split("~")
                if len(inner) < 45:
                    continue

                # 判断 A股 vs 美股: 美股 [0]="200", A股 [0]="1" 或 "51"
                is_us = inner[0] == "200"
                name = inner[1]
                code_field = inner[2]  # 如 "600519" 或 "NVDA.OQ"
                price = _safe_float(inner[3])
                yesterday_close = _safe_float(inner[4])
                change_pct = _safe_float(inner[32])  # 涨跌幅(%)

                # 提取 symbol key: "v_sh600519=" → "sh600519"
                sym_key = line.split("=")[0].strip() if "=" in line else ""
                if sym_key.startswith("v_"):
                    sym_key = sym_key[2:]

                pe = 0
                market_cap = 0

                if is_us:
                    # 美股字段:
                    # [39] = PE(TTM, 如 32.33)
                    # [62] = 总股本(股数), 市值 = price * [62]
                    pe = _safe_float(inner[39])
                    total_shares = _safe_float(inner[62]) if len(inner) > 62 else 0
                    market_cap = int(price * total_shares) if total_shares > 0 and price > 0 else 0
                else:
                    # A股字段:
                    # [52] = PE(静态市盈率, 如 15.02)
                    # [44] = 总市值(亿元) — 需转换为元
                    pe = _safe_float(inner[52]) if len(inner) > 52 else 0
                    mcap_yi = _safe_float(inner[44])
                    market_cap = int(mcap_yi * 1e8) if mcap_yi > 0 else 0

                if price > 0:
                    result[sym_key] = {
                        "name": name,
                        "code": code_field,
                        "price": round(price, 4),
                        "change_pct": round(change_pct, 2),
                        "pe": round(pe, 2) if pe > 0 else 0,
                        "market_cap": market_cap,
                        "is_us": is_us,
                    }

        except Exception as e:
            print(f"  [tencent] batch error: {e}", flush=True)

        # 每批之间间隔 0.3s
        if i + batch_size < total:
            time.sleep(0.3)

    return result


